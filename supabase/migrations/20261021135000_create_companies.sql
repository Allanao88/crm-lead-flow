create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  cnpj text,
  website text,
  email text,
  phone text,
  industry text,
  address text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint companies_name_not_blank check (length(trim(name)) > 0)
);

create index if not exists companies_user_id_idx
  on public.companies (user_id);

create index if not exists companies_name_idx
  on public.companies (user_id, name);

alter table public.companies enable row level security;

drop policy if exists "Users can view their own companies"
  on public.companies;
create policy "Users can view their own companies"
  on public.companies for select
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert their own companies"
  on public.companies;
create policy "Users can insert their own companies"
  on public.companies for insert
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own companies"
  on public.companies;
create policy "Users can update their own companies"
  on public.companies for update
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own companies"
  on public.companies;
create policy "Users can delete their own companies"
  on public.companies for delete
  using ((select auth.uid()) = user_id);

grant select, insert, update, delete
  on public.companies to authenticated;

