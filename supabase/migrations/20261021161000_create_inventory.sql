BEGIN;

-- Produtos do estoque compartilhado.
CREATE TABLE public.inventory_products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(btrim(name)) > 0),
    sku text UNIQUE,
    description text,
    unit text NOT NULL DEFAULT 'un' CHECK (length(btrim(unit)) > 0),
    average_cost numeric(14,4) NOT NULL DEFAULT 0 CHECK (average_cost >= 0),
    is_active boolean NOT NULL DEFAULT true,
    created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Produtos e quantidades vinculados explicitamente a cada lead.
CREATE TABLE public.lead_products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id bigint NOT NULL
        REFERENCES public.leads(id) ON DELETE RESTRICT,
    product_id bigint NOT NULL
        REFERENCES public.inventory_products(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT lead_products_lead_product_unique UNIQUE (lead_id, product_id)
);

CREATE INDEX lead_products_product_id_idx
    ON public.lead_products(product_id);

-- Livro-razão: entradas positivas e saídas negativas.
CREATE TABLE public.inventory_movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL
        REFERENCES public.inventory_products(id) ON DELETE RESTRICT,
    lead_id bigint
        REFERENCES public.leads(id) ON DELETE RESTRICT,
    movement_type text NOT NULL CHECK (
        movement_type IN (
            'entry',
            'exit',
            'reversal_entry',
            'reversal_exit'
        )
    ),
    quantity_delta numeric(14,3) NOT NULL CHECK (quantity_delta <> 0),
    unit_cost numeric(14,4) NOT NULL CHECK (unit_cost >= 0),
    total_cost numeric(14,4) NOT NULL CHECK (total_cost >= 0),
    reason text NOT NULL CHECK (length(btrim(reason)) > 0),
    reference_movement_id bigint
        REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
    created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT inventory_movements_sign_check CHECK (
        (movement_type IN ('entry', 'reversal_entry') AND quantity_delta > 0)
        OR
        (movement_type IN ('exit', 'reversal_exit') AND quantity_delta < 0)
    )
);

CREATE INDEX inventory_movements_product_created_idx
    ON public.inventory_movements(product_id, created_at, id);

CREATE INDEX inventory_movements_lead_id_idx
    ON public.inventory_movements(lead_id)
    WHERE lead_id IS NOT NULL;

-- Uma única saída automática por produto e lead, mesmo após reabertura do lead.
CREATE UNIQUE INDEX inventory_movements_one_lead_exit_idx
    ON public.inventory_movements(lead_id, product_id)
    WHERE lead_id IS NOT NULL
      AND movement_type = 'exit';

-- Cada movimentação pode ser estornada no máximo uma vez.
CREATE UNIQUE INDEX inventory_movements_one_reversal_idx
    ON public.inventory_movements(reference_movement_id)
    WHERE reference_movement_id IS NOT NULL;

-- O saldo é sempre calculado a partir do histórico.
CREATE VIEW public.inventory_stock_balances AS
SELECT
    p.id AS product_id,
    COALESCE(SUM(m.quantity_delta), 0)::numeric(14,3) AS quantity_on_hand
FROM public.inventory_products AS p
LEFT JOIN public.inventory_movements AS m
    ON m.product_id = p.id
GROUP BY p.id;

-- Não permitir alteração dos itens de um lead já ganho.
CREATE FUNCTION public.guard_lead_products_for_won_lead()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
    v_stage text;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        SELECT stage
          INTO v_stage
          FROM public.leads
         WHERE id = OLD.lead_id
         FOR UPDATE;

        IF v_stage = 'Ganho' THEN
            RAISE EXCEPTION
                'Não é permitido alterar os produtos de um lead ganho.';
        END IF;
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        SELECT stage
          INTO v_stage
          FROM public.leads
         WHERE id = NEW.lead_id
         FOR UPDATE;

        IF v_stage = 'Ganho' THEN
            RAISE EXCEPTION
                'Não é permitido alterar os produtos de um lead ganho.';
        END IF;

        RETURN NEW;
    END IF;

    RETURN OLD;
END;
$$;

CREATE TRIGGER lead_products_guard_won_lead
BEFORE INSERT OR UPDATE OR DELETE ON public.lead_products
FOR EACH ROW
EXECUTE FUNCTION public.guard_lead_products_for_won_lead();

-- O histórico é imutável: correções serão feitas por estornos.
CREATE FUNCTION public.prevent_inventory_movement_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
    RAISE EXCEPTION
        'O histórico de movimentações é imutável. Registre um estorno para corrigir.';
END;
$$;

CREATE TRIGGER inventory_movements_immutable
BEFORE UPDATE OR DELETE ON public.inventory_movements
FOR EACH ROW
EXECUTE FUNCTION public.prevent_inventory_movement_mutation();

-- RLS: estoque compartilhado entre usuários autenticados.
ALTER TABLE public.inventory_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lead_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventory_movements ENABLE ROW LEVEL SECURITY;

CREATE POLICY inventory_products_select_authenticated
    ON public.inventory_products
    FOR SELECT TO authenticated
    USING (true);

CREATE POLICY inventory_products_insert_authenticated
    ON public.inventory_products
    FOR INSERT TO authenticated
    WITH CHECK (true);

CREATE POLICY inventory_products_update_authenticated
    ON public.inventory_products
    FOR UPDATE TO authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY lead_products_select_authenticated
    ON public.lead_products
    FOR SELECT TO authenticated
    USING (true);

CREATE POLICY lead_products_insert_authenticated
    ON public.lead_products
    FOR INSERT TO authenticated
    WITH CHECK (true);

CREATE POLICY lead_products_update_authenticated
    ON public.lead_products
    FOR UPDATE TO authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY lead_products_delete_authenticated
    ON public.lead_products
    FOR DELETE TO authenticated
    USING (true);

CREATE POLICY inventory_movements_select_authenticated
    ON public.inventory_movements
    FOR SELECT TO authenticated
    USING (true);

-- A view permite consultar o saldo sem conceder escrita no livro-razão.
GRANT SELECT ON public.inventory_stock_balances TO authenticated;

COMMIT;
