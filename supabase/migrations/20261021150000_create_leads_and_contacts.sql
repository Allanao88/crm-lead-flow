BEGIN;

CREATE TABLE public.leads (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text,
    phone text,
    company text,
    stage text NOT NULL DEFAULT 'Novo lead',
    value numeric NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    setup_value numeric NOT NULL DEFAULT 0,
    mrr_value numeric NOT NULL DEFAULT 0
);

CREATE TABLE public.contacts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text,
    phone text,
    company text,
    job_title text,
    notes text,
    source text,
    lead_id bigint REFERENCES public.leads(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX contacts_lead_id_idx ON public.contacts (lead_id);
CREATE INDEX contacts_name_idx ON public.contacts (name);

ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;

CREATE POLICY leads_select_authenticated
    ON public.leads FOR SELECT TO authenticated USING (true);

CREATE POLICY leads_insert_authenticated
    ON public.leads FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY contacts_select_authenticated
    ON public.contacts FOR SELECT TO authenticated USING (true);

CREATE POLICY contacts_insert_authenticated
    ON public.contacts FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY contacts_update_authenticated
    ON public.contacts FOR UPDATE TO authenticated
    USING (true) WITH CHECK (true);

CREATE POLICY contacts_delete_authenticated
    ON public.contacts FOR DELETE TO authenticated USING (true);

GRANT SELECT, INSERT ON public.leads TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.contacts TO authenticated;

COMMIT;
